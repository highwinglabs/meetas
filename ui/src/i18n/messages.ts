export const MESSAGES: Record<UiLang, Record<MessageKey, string>> = { de, en };

export function systemLang(): UiLang {
  const nav = (typeof navigator !== "undefined" && navigator.language) || "";
  return nav.toLowerCase().startsWith("de") ? "de" : "en";
}

export function resolveLang(pref: LangPref): UiLang {
  return pref === "de" || pref === "en" ? pref : systemLang();
}

export function format(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => {
    const value = vars[name];
    return value == null ? whole : String(value);
  });
}

export function translate(lang: UiLang, key: MessageKey, vars?: Record<string, string | number>): string {
  const template = MESSAGES[lang][key] ?? MESSAGES.de[key] ?? key;
  return format(template, vars);
}

// Module-level active language. Kept in sync by the I18nProvider so that
// non-React modules (api.ts, format.ts) can localise without the hook.
let active: UiLang = resolveLang("system");

export function setActiveLang(lang: UiLang): void {
  active = lang;
}

export function activeLang(): UiLang {
  return active;
}

export function msg(key: MessageKey, vars?: Record<string, string | number>): string {
  return translate(active, key, vars);
}

export function uiLocale(lang: UiLang): string {
  return lang === "en" ? "en-GB" : "de-DE";
}

export function activeLocale(): string {
  return uiLocale(active);
}
